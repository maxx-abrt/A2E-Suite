import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';

import pg from 'pg';

import {
  inspectColumnSlots,
  recoverColumnSlots,
} from '../../../twenty-server/scripts/recover-column-slots.mjs';

const testUrl = new URL(process.env.A2E_RECOVERY_TEST_URL ?? 'invalid');
if (
  !['localhost', '127.0.0.1', '[::1]'].includes(testUrl.hostname) ||
  testUrl.pathname !== '/test'
)
  throw new Error(
    'A2E_RECOVERY_TEST_URL must select the disposable local test database',
  );

test('reclaims 1,593 dropped slots through a verified logical clone, preserving the original', async () => {
  const identifier = randomBytes(6).toString('hex');
  const sourceName = `a2e_column_test_source_${identifier}`;
  const targetName = `a2e_column_test_target_${identifier}`;
  const directory = mkdtempSync(join(tmpdir(), 'a2e-column-recovery-test-'));
  const administrationUrl = new URL(testUrl);
  administrationUrl.pathname = '/postgres';
  const sourceUrl = new URL(testUrl);
  sourceUrl.pathname = `/${sourceName}`;
  const targetUrl = new URL(testUrl);
  targetUrl.pathname = `/${targetName}`;
  const administration = new pg.Client({
    connectionString: administrationUrl.href,
  });
  let source;
  let target;
  await administration.connect();
  try {
    await administration.query(
      `CREATE DATABASE "${sourceName}" TEMPLATE template0`,
    );
    source = new pg.Client({ connectionString: sourceUrl.href });
    await source.connect();
    await source.query(`
      CREATE SCHEMA core;
      CREATE SCHEMA workspace_recovery;
      CREATE TYPE core.task_status AS ENUM ('TODO', 'DONE');
      CREATE TABLE workspace_recovery.task (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title text NOT NULL,
        status core.task_status NOT NULL DEFAULT 'TODO',
        "parentId" integer REFERENCES workspace_recovery.task(id) ON DELETE SET NULL,
        body jsonb,
        "searchVector" tsvector GENERATED ALWAYS AS (to_tsvector('simple', title)) STORED,
        "createdAt" timestamptz NOT NULL DEFAULT now()
      );
      CREATE INDEX task_title_index ON workspace_recovery.task(title);
      CREATE TABLE core.activity (id integer PRIMARY KEY, "taskId" integer REFERENCES workspace_recovery.task(id));
      CREATE VIEW core.task_titles AS SELECT title FROM workspace_recovery.task;
      CREATE TABLE core.audit (title text);
      CREATE FUNCTION core.audit_task() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN INSERT INTO core.audit VALUES (NEW.title); RETURN NEW; END $$;
      CREATE TRIGGER audit_task AFTER UPDATE ON workspace_recovery.task FOR EACH ROW EXECUTE FUNCTION core.audit_task();
      ALTER TABLE workspace_recovery.task ENABLE ROW LEVEL SECURITY;
      CREATE POLICY task_policy ON workspace_recovery.task USING (id > 0);
      INSERT INTO workspace_recovery.task(title, body) VALUES ('Équipe — réunion', '{"nested":[1,true,null]}');
      INSERT INTO workspace_recovery.task(title, "parentId") VALUES ('Second task', 1);
      INSERT INTO core.activity VALUES (1, 2);
    `);
    const unusedColumns = Array.from(
      { length: 1593 },
      (_, index) => `unused_${index}`,
    );
    await source.query(
      `ALTER TABLE workspace_recovery.task ${unusedColumns.map((name) => `ADD COLUMN "${name}" integer`).join(', ')}`,
    );
    await source.query(
      `ALTER TABLE workspace_recovery.task ${unusedColumns.map((name) => `DROP COLUMN "${name}"`).join(', ')}`,
    );
    await assert.rejects(
      source.query(
        'ALTER TABLE workspace_recovery.task ADD COLUMN "blockedById" uuid',
      ),
      /at most 1600 columns/,
    );
    const sourceRows = (
      await source.query('SELECT * FROM workspace_recovery.task ORDER BY id')
    ).rows;
    const options = {
      connectionString: sourceUrl.href,
      targetDatabase: targetName,
      directory,
      log: () => {},
    };
    const plan = await recoverColumnSlots(options);
    assert.equal(plan.applied, false);
    assert.equal(plan.exhausted[0].slots, 1600);
    assert.equal(plan.exhausted[0].dropped, 1593);
    await assert.rejects(
      recoverColumnSlots({ ...options, apply: true }),
      /Stop every API, worker/,
    );
    await source.end();
    source = undefined;

    const result = await recoverColumnSlots({ ...options, apply: true });
    assert.equal(result.applied, true);
    assert.equal(statSync(result.backupDirectory).mode & 0o777, 0o700);
    assert.equal(
      statSync(join(result.backupDirectory, 'source.dump')).mode & 0o777,
      0o600,
    );
    assert.equal(
      JSON.parse(
        readFileSync(join(result.backupDirectory, 'verified.json'), 'utf8'),
      ).targetDatabase,
      targetName,
    );
    target = new pg.Client({ connectionString: targetUrl.href });
    await target.connect();
    assert.deepEqual(
      (await target.query('SELECT * FROM workspace_recovery.task ORDER BY id'))
        .rows,
      sourceRows,
    );
    const taskSlots = (await inspectColumnSlots(target)).find(
      (table) => table.table === 'task',
    );
    assert.deepEqual(taskSlots, {
      schema: 'workspace_recovery',
      table: 'task',
      slots: 7,
      active: 7,
      dropped: 0,
    });
    await target.query(
      'ALTER TABLE workspace_recovery.task ADD COLUMN "blockedById" uuid',
    );
    assert.equal(
      (
        await target.query(
          "INSERT INTO workspace_recovery.task(title) VALUES ('Next identity') RETURNING id",
        )
      ).rows[0].id,
      3,
    );
    await assert.rejects(
      target.query('INSERT INTO core.activity VALUES (2, 999)'),
      { code: '23503' },
    );
    await target.query(
      "UPDATE workspace_recovery.task SET title = 'Updated' WHERE id = 1",
    );
    assert.equal(
      (await target.query('SELECT title FROM core.audit')).rows[0].title,
      'Updated',
    );
    assert.equal(
      (
        await target.query(
          'SELECT count(*)::int AS count FROM core.task_titles',
        )
      ).rows[0].count,
      3,
    );
    assert.equal(
      (
        await target.query(
          "SELECT count(*)::int AS count FROM pg_policies WHERE policyname = 'task_policy'",
        )
      ).rows[0].count,
      1,
    );
    assert.equal(
      (
        await target.query(
          "SELECT count(*)::int AS count FROM pg_indexes WHERE indexname = 'task_title_index'",
        )
      ).rows[0].count,
      1,
    );
    await assert.rejects(
      recoverColumnSlots({ ...options, apply: true }),
      /already exists/,
    );
    source = new pg.Client({ connectionString: sourceUrl.href });
    await source.connect();
    assert.deepEqual(
      (await source.query('SELECT * FROM workspace_recovery.task ORDER BY id'))
        .rows,
      sourceRows,
    );
    await assert.rejects(
      source.query(
        'ALTER TABLE workspace_recovery.task ADD COLUMN "blockedById" uuid',
      ),
      /at most 1600 columns/,
    );
  } finally {
    await target?.end();
    await source?.end();
    for (const databaseName of [targetName, sourceName])
      await administration.query(
        `DROP DATABASE IF EXISTS "${databaseName}" WITH (FORCE)`,
      );
    await administration.end();
    rmSync(directory, { recursive: true, force: true });
  }
});
